"""Turn an Etsy "Download listings" CSV into products.js for the shop.

Usage: python3 scripts/import_etsy.py EtsyListingsDownload.csv
"""
import csv, json, re, sys

CATEGORIES = [  # first match wins
    ("Horror & Halloween", r"horror|halloween|spooky|zombie|witch|mummy|krueger|insidious|scream|claws"),
    ("Hands", r"\bhands?\b"),
    ("Pets", r"pug|dachshund|yorkie|terrier"),
    ("Sea Life", r"starfish|turtle|stingray|shark|crab|flamingo"),
    ("Animal Heads", r"head|bust|wall mount|rhino|hippo|bunny|rabbit|unicorn|owl"),
]

def category(title):
    for name, pattern in CATEGORIES:
        if re.search(pattern, title, re.I):
            return name
    return "Gifts & More"

def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:60]

rows = list(csv.DictReader(open(sys.argv[1], encoding="utf-8-sig")))
products, seen = [], set()
for r in rows:
    pid = slug(r["TITLE"])
    while pid in seen:
        pid += "-2"
    seen.add(pid)
    options = []
    for i in "123":
        name, values = r[f"VARIATION {i} NAME"].strip(), r[f"VARIATION {i} VALUES"].strip()
        if name and values:
            options.append({"name": name, "values": [v.strip() for v in values.split(",") if v.strip()]})
    products.append({
        "id": pid,
        "name": r["TITLE"].strip(),
        "category": category(r["TITLE"]),
        "price": round(float(r["PRICE"]), 2),
        "desc": r["DESCRIPTION"].strip(),
        "images": [r[f"IMAGE{i}"] for i in range(1, 11) if r[f"IMAGE{i}"]],
        "options": options,
    })

with open("products.js", "w") as f:
    f.write("// Generated by scripts/import_etsy.py from an Etsy listings export.\n")
    f.write("window.PRODUCTS = " + json.dumps(products, indent=1, ensure_ascii=False) + ";\n")
print(f"Wrote {len(products)} products")
